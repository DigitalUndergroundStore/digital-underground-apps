def wiki_url(title: str) -> str:
    slug = title.replace(" ", "_")
    return "https://en.wikibooks.org/wiki/" + urllib.parse.quote(slug, safe="()'%")


def main() -> None:
    known = {line.strip() for line in TITLES.read_text().splitlines() if line.strip()}
    recipes = {r["id"]: r for r in json.loads(RECIPES.read_text())}
    ids = [f"r{n}" for n in range(1, 249)]
    missing_ids = [i for i in ids if i not in SOURCED and i not in ORIGINALS]
    extra = [i for i in list(SOURCED) + list(ORIGINALS) if i not in recipes]
    if missing_ids or extra:
        raise SystemExit(f"map mismatch missing={missing_ids} extra={extra}")
    overlap = set(SOURCED) & set(ORIGINALS)
    if overlap:
        raise SystemExit(f"both sourced and original: {sorted(overlap)}")
    out = {}
    for rid in ids:
        old = recipes[rid]["name"]
        if rid in ORIGINALS:
            out[rid] = {
                "id": rid,
                "name": old,
                "newName": None,
                "original": True,
                "replaced": False,
                "pages": [],
                "licence": "original",
                "note": ORIGINALS[rid],
            }
            continue
        pages, note, new_name = SOURCED[rid]
        bad = [p for p in pages if p not in known]
        if bad:
            raise SystemExit(f"{rid} unknown pages: {bad}")
        sources = [{
            "title": p,
            "url": wiki_url(p),
            "licence": LICENCE,
            "licenceUrl": LICENCE_URL,
        } for p in pages]
        out[rid] = {
            "id": rid,
            "name": old,
            "newName": new_name,
            "original": False,
            "replaced": bool(new_name),
            "pages": pages,
            "licence": LICENCE,
            "licenceUrl": LICENCE_URL,
            "note": note,
            "sources": sources,
        }
    OUT.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n")
    n_orig = sum(1 for v in out.values() if v["original"])
    n_src = 248 - n_orig
    print(f"wrote {OUT} sourced={n_src} original={n_orig} replaced={sum(1 for v in out.values() if v['replaced'])}")


