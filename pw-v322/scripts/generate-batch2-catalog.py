def ing(qty, unit, item) -> dict:
    if isinstance(qty, str):
        return {"qty": qty, "unit": unit, "item": item}
    return {"qty": qty, "unit": unit, "item": item}


def fix_ingredients(rows):
    out = []
    for row in rows:
        q, u, it = row
        if isinstance(q, str) and q.endswith('"'):
            # typo pattern 1", "small" -> qty 1 unit empty item small
            pass
        if u in ("small", "large") and isinstance(q, (int, float)):
            out.append({"qty": q, "unit": "", "item": it})
        elif isinstance(q, str) and '"' in q:
            # malformed like 1", "yellow onion"
            num = q.replace('"', "").strip()
            try:
                qv = int(num) if num.isdigit() else float(num)
            except ValueError:
                qv = 1
            out.append({"qty": qv, "unit": "", "item": it})
        elif q == '1"':
            out.append({"qty": 1, "unit": "", "item": it})
        else:
            out.append(ing(q, u, it))
    return out


def main() -> None:
    catalog = []
    for num, name, minutes, servings, tags, ingredients, steps in RECIPES:
        rid = f"r{num}"
        catalog.append(
            {
                "id": rid,
                "name": name,
                "minutes": minutes,
                "servings": servings,
                "tags": tags,
                "ingredients": fix_ingredients(ingredients),
                "steps": steps,
            }
        )
    if len(catalog) != 48:
        raise SystemExit(f"expected 48 recipes, got {len(catalog)}")
    ids = [r["id"] for r in catalog]
    if ids != [f"r{i}" for i in range(201, 249)]:
        raise SystemExit("ids must be r201–r248 in order")
    OUT.write_text(json.dumps(catalog, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({len(catalog)} recipes)")


if __name__ == "__main__":
    main()
